const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
const path = require('node:path');

test('首次改密、分组项目、周报草稿、编辑冲突、归档恢复与导出', async ({ page }) => {
  const failures = [];
  page.on('pageerror', error => failures.push(error.message));
  await page.goto('/login');
  await page.locator('[name=username]').fill('admin');
  await page.locator('[name=password]').fill(fs.readFileSync(path.join(process.env.E2E_DATA_DIR, 'test-password'), 'utf8'));
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page).toHaveURL(/change-password/);
  const old = fs.readFileSync(path.join(process.env.E2E_DATA_DIR, 'test-password'), 'utf8');
  await page.locator('[name=old_password]').fill(old);
  await page.locator('[name=new_password]').fill('Browser-password-2026');
  await page.locator('[name=confirm_password]').fill('Browser-password-2026');
  await page.getByRole('button', { name: '保存并继续' }).click();
  await expect(page.locator('#dailyView')).toBeVisible();
  await page.locator('[data-view=groups]').click();
  await page.locator('#newGroupBtn').click();
  await page.locator('#newGroupForm [name=name]').fill('浏览器测试组');
  await page.locator('#newGroupForm [type=submit]').click();
  await expect(page.locator('#groupsList')).toContainText('浏览器测试组');
  await page.locator('[data-view=projects]').click();
  await page.locator('#newProjectBtn').click();
  await page.locator('#projectForm [name=name]').fill('端到端项目');
  await page.locator('#projectForm [name=group_id]').selectOption({ label: '浏览器测试组' });
  await page.locator('#projectForm [type=submit]').click();
  await page.locator('[data-write-report=weekly]').click();
  await page.locator('#reportForm [name=done]').fill('本周完成端到端验证');
  await expect(page.locator('#reportForm')).toContainText('草稿已保存');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#modalRoot [data-close][aria-label=关闭]').click();
  await page.locator('[data-open-project]').click();
  await page.locator('[data-write-report=weekly]').click();
  await page.getByRole('button', { name: '恢复未提交草稿' }).click();
  await expect(page.locator('#reportForm [name=done]')).toHaveValue('本周完成端到端验证');
  await page.locator('#reportForm [type=submit]').click();
  await expect(page.locator('.report-card')).toContainText('本周完成端到端验证');
  await expect(page.locator('[data-project-tab=weekly]')).toHaveClass(/active/);
  await page.locator('[data-edit-report]').click();
  const projectId = new URL(page.url()).hash.split('/')[1];
  const list = await (await page.request.get(`/api/projects/${projectId}/reports?type=weekly`)).json();
  const existing = list.reports[0];
  expect((await page.request.patch(`/api/reports/${existing.id}`, { data: { done: '另一窗口已保存', version: existing.version } })).status()).toBe(200);
  await page.locator('#reportForm [name=done]').fill('旧窗口不应覆盖');
  await page.locator('#reportForm [type=submit]').click();
  await expect(page.locator('#toastRoot')).toContainText('内容已被其他人修改');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#modalRoot [data-close][aria-label=关闭]').click();
  await page.reload();
  await page.locator('[data-edit-report]').click();
  await page.locator('#reportForm [name=done]').fill('周报修改成功');
  await page.locator('#reportForm [type=submit]').click();
  await expect(page.locator('.report-card')).toContainText('周报修改成功');
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: '导出 Excel', exact: true }).click();
  expect((await download).suggestedFilename()).toMatch(/\.xlsx$/);
  page.once('dialog', dialog => dialog.accept());
  await page.locator('[data-archive-project]').click();
  await page.locator('#projectStatusFilter').selectOption('archived');
  await page.locator('[data-open-project]').click();
  await expect(page.locator('[data-write-report]')).toHaveCount(0);
  await page.locator('#restoreProject').click();
  await expect(page.locator('[data-write-report=weekly]')).toBeVisible();
  await page.locator('#modalRoot [data-close][aria-label=关闭]').click();
  await page.locator('[data-view=items]').click();
  await expect(page.locator('#itemsTable')).not.toContainText('服务器错误');
  await expect(page.locator('#itemsNext')).toBeVisible();
  await page.locator('#auditBtn').click();
  await expect(page.locator('#modalRoot')).toContainText('updateReport');
  await page.locator('#modalRoot [data-close][aria-label=关闭]').click();
  await page.goto(`/#project/${projectId}/weekly`);
  await expect(page.locator('[data-write-report=weekly]')).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('#modalRoot .modal')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/mobile-project.png', fullPage: true });
  expect(failures).toEqual([]);
});
